import type { ReactNode } from 'react';

/** "In plain words": a short sentence a first-time visitor can read before looking at the chart. */
export function Explainer({ title = 'In plain words', children, tone = 'signal', className = '' }: { title?: string; children: ReactNode; tone?: 'signal' | 'solar' | 'biosphere' | 'alert'; className?: string }) {
  return (
    <aside className={`pl-4 py-1 ${className}`} style={{ borderLeft: `2px solid var(--${tone})` }}>
      <div className="label mb-1" style={{ color: `var(--${tone})` }}>{title}</div>
      <div className="text-[15px] text-text/90 leading-relaxed max-w-prose">{children}</div>
    </aside>
  );
}

type CaveatKind = 'SIMULATED' | 'VERIFIED_MEANING' | 'CROSS_TISSUE_SAME_COHORT' | 'HYPOTHESIS_ONLY' | 'INTERNAL_REPLICATION' | 'POWER';

const TEXT: Record<CaveatKind, { tone: string; head: string; body: string }> = {
  SIMULATED: { tone: 'solar', head: 'SIMULATED', body: 'The outcome in this analysis was generated by SYNERA with known planted interactions. It measures the engine, not nature, and can never be VERIFIED.' },
  VERIFIED_MEANING: { tone: 'biosphere', head: 'WHAT VERIFIED MEANS', body: 'Statistically validated with verified computational provenance. It does not mean biologically proven.' },
  CROSS_TISSUE_SAME_COHORT: { tone: 'solar', head: 'CROSS-TISSUE · SAME COHORT', body: 'The same animals contributed both tissues, so agreement between them is a consistency check, not independent replication.' },
  HYPOTHESIS_ONLY: { tone: 'alert', head: 'HYPOTHESIS ONLY', body: 'No replication was possible. Treat this as a hypothesis to test, not a result.' },
  INTERNAL_REPLICATION: { tone: 'solar', head: 'INTERNAL REPLICATION', body: 'Replicated within the same dataset (held-out cities). Independent replication has not been attempted.' },
  POWER: { tone: 'signal', head: 'LOW POWER', body: 'With so few samples per group only large interactions can be detected. Absence of a finding is not evidence of absence.' },
};

export function Caveat({ kind, children }: { kind: CaveatKind; children?: ReactNode }) {
  const t = TEXT[kind];
  return (
    <div role="note" className="flex gap-3 items-start border border-line px-4 py-2.5 bg-void/50" style={{ borderLeft: `2px solid var(--${t.tone})` }}>
      <span className="num text-[10px] tracking-[0.16em] whitespace-nowrap mt-0.5" style={{ color: `var(--${t.tone})` }}>{t.head}</span>
      <span className="text-[13px] text-muted leading-snug">{children ?? t.body}</span>
    </div>
  );
}
